def resolve(name, coords=None):
    """航点名 → (lat,lng,matched_key) 或 None。
    尝试序：全名 → 剥郡前缀 → 子串右对齐 → 裁尾缀方位（县南/之尧/…）后重试。"""
    coords = coords or all_coords()
    if not name or name == "前县":
        return None
    r = _try(name, coords)
    if r:
        return r
    # 裁尾缀方位词后重试（「桂阳郴县南」→「郴县」）
    for t in ("东南", "东北", "西南", "西北", "县南", "县北", "县东", "县西",
              "关东", "之尧", "谷中", "县江", "之东", "之南", "之西", "之北",
              "南", "北", "东", "西", "中"):
        if name.endswith(t) and len(name) > len(t) + 1:
            r = _try(name[:-len(t)], coords)
            if r:
                return r
    return None

def _try(name, coords):
    if not name or name == "前县":
        return None
    if name in coords:
        return coords[name][0], coords[name][1], name
    for j in JUN_PREFIX:
        if name.startswith(j) and len(name) > len(j):
            stripped = name[len(j):]
            if stripped in coords:
                return coords[stripped][0], coords[stripped][1], stripped
    best = None
    for k, v in coords.items():
        if len(k) >= 2 and name.endswith(k) and name != k:
            if best is None or len(k) > len(best[2]):
                best = (v[0], v[1], k)
    return best

